import type { Recipe, RecipeIngredient, Unit } from '../types';

// Seed recipes for Pink Kitchen. Nutrition is NOT stored here — the app
// computes it from ingredient quantities using the ingredient catalog.
// Every `ingredientId` must exist in ./ingredients.ts.

const SEED_DATE = '2026-11-12T00:00:00.000Z';

type SeedInput = Omit<Recipe, 'isSeed' | 'createdAt' | 'updatedAt'>;

function r(x: SeedInput): Recipe {
  return { ...x, isSeed: true, createdAt: SEED_DATE, updatedAt: SEED_DATE };
}

/** Ingredient line helper. */
function i(ingredientId: string, quantity: number, unit: Unit, extra: { optional?: boolean; note?: string } = {}): RecipeIngredient {
  return { ingredientId, quantity, unit, ...extra };
}
/** Optional ingredient line helper. */
function o(ingredientId: string, quantity: number, unit: Unit, note?: string): RecipeIngredient {
  return { ingredientId, quantity, unit, optional: true, ...(note ? { note } : {}) };
}

